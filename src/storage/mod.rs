//! The storage interface: one way to talk to the database, two engines.
//!
//! The single-machine program stores its data in SQLite; the Kubernetes
//! chart uses PostgreSQL. Services never talk to either directly. They use
//! [`AsyncStore`], write SQL in the shared subset below, and run on both.
//!
//! The interface is async. Code that is not async uses the same stores
//! through [`blocking`].
//!
//! The shared subset:
//! - Parameters are written `$1`, `$2`, ... in every statement.
//! - Column types are `BIGINT`, `TEXT` and `{{blob}}` (binary data). There
//!   is no boolean and no timestamp type: use `BIGINT` 0/1 and Unix
//!   milliseconds.
//! - Keys are declared as `PRIMARY KEY` on `BIGINT` or `TEXT` columns; ids
//!   are generated by the caller, not by the database.

