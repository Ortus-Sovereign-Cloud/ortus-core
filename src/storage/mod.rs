//! The storage interface: one way to talk to the database, two engines.
//!
//! The single-machine program stores its data in SQLite; the Kubernetes
//! chart uses PostgreSQL. Services never talk to either directly. They use
//! [`Store`], write SQL in the shared subset below, and run on both.
//!
//! The shared subset:
//! - Parameters are written `$1`, `$2`, ... in every statement.
//! - Column types are `BIGINT`, `TEXT` and `{{blob}}` (binary data). There
//!   is no boolean and no timestamp type: use `BIGINT` 0/1 and Unix
//!   milliseconds.
//! - Keys are declared as `PRIMARY KEY` on `BIGINT` or `TEXT` columns; ids
//!   are generated by the caller, not by the database.

mod migrate;
mod postgres;
mod sqlite;

pub use migrate::{applied_versions, migrate, Migration};
pub use postgres::PostgresStore;
pub use sqlite::SqliteStore;

use std::fmt;

/// Which database engine a store runs on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Engine {
    Sqlite,
    Postgres,
}

/// A value sent to or read from the database.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Value {
    Null,
    Int(i64),
    Text(String),
    Blob(Vec<u8>),
}

impl Value {
    pub fn as_int(&self) -> Option<i64> {
        match self {
            Value::Int(v) => Some(*v),
            _ => None,
        }
    }

    pub fn as_text(&self) -> Option<&str> {
        match self {
            Value::Text(v) => Some(v),
            _ => None,
        }
    }

    pub fn as_blob(&self) -> Option<&[u8]> {
        match self {
            Value::Blob(v) => Some(v),
            _ => None,
        }
    }

    pub fn is_null(&self) -> bool {
        matches!(self, Value::Null)
    }
}

impl From<i64> for Value {
    fn from(v: i64) -> Self {
        Value::Int(v)
    }
}

impl From<&str> for Value {
    fn from(v: &str) -> Self {
        Value::Text(v.to_string())
    }
}

impl From<String> for Value {
    fn from(v: String) -> Self {
        Value::Text(v)
    }
}

impl From<Vec<u8>> for Value {
    fn from(v: Vec<u8>) -> Self {
        Value::Blob(v)
    }
}

impl<T: Into<Value>> From<Option<T>> for Value {
    fn from(v: Option<T>) -> Self {
        v.map_or(Value::Null, Into::into)
    }
}

/// One row of a query result, in the order the columns were selected.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row(pub Vec<Value>);

impl Row {
    /// The value in column `index`, or `Null` when the row is shorter.
    pub fn get(&self, index: usize) -> &Value {
        self.0.get(index).unwrap_or(&Value::Null)
    }

    pub fn int(&self, index: usize) -> Option<i64> {
        self.get(index).as_int()
    }

    pub fn text(&self, index: usize) -> Option<&str> {
        self.get(index).as_text()
    }

    pub fn blob(&self, index: usize) -> Option<&[u8]> {
        self.get(index).as_blob()
    }
}

/// A storage failure.
#[derive(Debug)]
pub enum StoreError {
    /// A row with the same key already exists.
    Conflict(String),
    /// Anything else the database reported.
    Database(String),
    /// A migration list is wrong: a gap, a reorder, or a changed history.
    Migration(String),
}

impl fmt::Display for StoreError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            StoreError::Conflict(m) => write!(f, "conflict: {m}"),
            StoreError::Database(m) => write!(f, "database: {m}"),
            StoreError::Migration(m) => write!(f, "migration: {m}"),
        }
    }
}

impl std::error::Error for StoreError {}

pub type StoreResult<T> = Result<T, StoreError>;

/// Statements that run inside one transaction.
pub trait Tx {
    /// Runs a statement and returns the number of rows it changed.
    fn execute(&mut self, sql: &str, params: &[Value]) -> StoreResult<u64>;
    /// Runs a query and returns its rows.
    fn query(&mut self, sql: &str, params: &[Value]) -> StoreResult<Vec<Row>>;
}

/// A database. Implemented for SQLite and PostgreSQL; services depend on
/// this trait only.
pub trait Store: Send + Sync {
    fn engine(&self) -> Engine;

    /// Runs `work` in a transaction. The transaction commits when `work`
    /// returns `Ok` and rolls back when it returns `Err`.
    fn transaction(&self, work: &mut dyn FnMut(&mut dyn Tx) -> StoreResult<()>) -> StoreResult<()>;

    /// Runs one statement in its own transaction.
    fn execute(&self, sql: &str, params: &[Value]) -> StoreResult<u64> {
        let mut changed = 0;
        self.transaction(&mut |tx| {
            changed = tx.execute(sql, params)?;
            Ok(())
        })?;
        Ok(changed)
    }

    /// Runs one query in its own transaction.
    fn query(&self, sql: &str, params: &[Value]) -> StoreResult<Vec<Row>> {
        let mut rows = Vec::new();
        self.transaction(&mut |tx| {
            rows = tx.query(sql, params)?;
            Ok(())
        })?;
        Ok(rows)
    }
}

/// Rewrites shared-subset SQL for one engine: `{{blob}}` becomes the
/// engine's binary type, and for SQLite `$n` becomes `?n`. Text inside
/// single-quoted literals is left alone.
pub(crate) fn dialect(sql: &str, engine: Engine) -> String {
    let blob = match engine {
        Engine::Sqlite => "BLOB",
        Engine::Postgres => "BYTEA",
    };
    let sql = sql.replace("{{blob}}", blob);
    if engine == Engine::Postgres {
        return sql;
    }
    let mut out = String::with_capacity(sql.len());
    let mut in_literal = false;
    let mut chars = sql.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\'' {
            in_literal = !in_literal;
            out.push(c);
        } else if c == '$' && !in_literal && chars.peek().is_some_and(char::is_ascii_digit) {
            out.push('?');
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sqlite_dialect_rewrites_parameters_outside_literals() {
        let sql = "SELECT '$1 stays', a FROM t WHERE a = $1 AND b = $12";
        assert_eq!(
            "SELECT '$1 stays', a FROM t WHERE a = ?1 AND b = ?12",
            dialect(sql, Engine::Sqlite)
        );
        assert_eq!(sql, dialect(sql, Engine::Postgres));
    }

    #[test]
    fn blob_type_is_named_per_engine() {
        assert_eq!("d BLOB", dialect("d {{blob}}", Engine::Sqlite));
        assert_eq!("d BYTEA", dialect("d {{blob}}", Engine::Postgres));
    }
}
